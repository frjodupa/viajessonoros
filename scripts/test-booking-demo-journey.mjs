import assert from 'node:assert/strict';
import {createBookingDemoJourney} from '../src/booking-demo-journey.js';
let journey=createBookingDemoJourney({capacity:3,initialConfirmed:2});
assert.equal(journey.overview().available,1);
assert.equal(journey.submit({seats:2}).status,'pending');
assert.deepEqual(journey.decide('confirm'),{changed:false,reason:'CAPACITY_EXCEEDED'});
assert.equal(journey.overview().confirmed,2);
assert.deepEqual(journey.decide('cancel'),{changed:true,status:'cancelled'});
assert.equal(journey.overview().available,1);
assert.equal(journey.overview().pending,0);
journey.reset();
assert.equal(journey.overview().request,null);
journey.submit({seats:1});
assert.deepEqual(journey.decide('confirm'),{changed:true,status:'confirmed'});
assert.equal(journey.overview().available,0);
assert.deepEqual(journey.decide('confirm'),{changed:false,reason:'INVALID_TRANSITION'});
assert.equal(journey.overview().request.status,'confirmed');
assert.equal(JSON.stringify(journey.overview()).includes('phone'),false);
assert.throws(()=>createBookingDemoJourney({capacity:1,initialConfirmed:2}),/INVALID_CAPACITY/);
console.log('PASS: shared demo journey enforces capacity and status transitions');
