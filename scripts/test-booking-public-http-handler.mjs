import assert from 'node:assert/strict';
import {createPublicBookingHttpHandler} from '../src/booking-public-http-handler.js';
let saved=0;
const handler=createPublicBookingHttpHandler({verifyAbuse:async()=>true,register:async d=>{saved++;return{saved:true,status:'pending',eventId:d.eventId,reference:'BOOK-987654'}}});
const request=body=>new Request('https://example.test/api/public/bookings',{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify(body)});
const ok=await handler(request({eventId:'e1',name:'Ejemplo',phone:'600000000',seats:1}));
assert.equal(ok.status,201);assert.deepEqual(await ok.json(),{saved:true,status:'pending',eventId:'e1',reference:'BOOK-987654'});
assert.equal(saved,1);
const blocked=createPublicBookingHttpHandler({verifyAbuse:async()=>false,register:async()=>{throw Error('SHOULD_NOT_RUN')}});
assert.equal((await blocked(request({}))).status,429);
assert.throws(()=>createPublicBookingHttpHandler({register:async()=>({})}),/PUBLIC_SECURITY_DEPENDENCIES_REQUIRED/);
assert.equal((await handler(new Request('https://example.test/',{method:'GET'}))).status,405);
const fails=createPublicBookingHttpHandler({verifyAbuse:async()=>true,register:async()=>({saved:false,error:'DUPLICATE_ACTIVE_REQUEST'})});
assert.equal((await fails(request({}))).status,409);
console.log('PASS: public HTTP adapter guarded, no false registration, no deployed route');
